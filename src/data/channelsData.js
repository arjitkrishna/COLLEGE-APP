export const getChannelsForBranch = (branch = 'CSE') => {
  const branchList = BRANCH_CHANNELS[branch] || BRANCH_CHANNELS.CSE;
  return [...GENERAL_CHANNELS, ...branchList];
};

export const getChannelById = (channelId) => {
  const allChannels = [
    ...GENERAL_CHANNELS,
    ...BRANCH_CHANNELS.CSE,
    ...BRANCH_CHANNELS.DSAI,
    ...BRANCH_CHANNELS.ECE,
  ];
  return allChannels.find((ch) => ch.id === channelId) || allChannels[0];
};

export const getMessagesForChannel = (channelId) => {
  return mockMessages[channelId] || [];
};

export const getTotalUnreadMessages = (branch = 'CSE') => {
  const channels = getChannelsForBranch(branch);
  return channels.reduce((total, ch) => total + (ch.unreadCount || 0), 0);
};

